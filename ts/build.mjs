// Build: strip the types from src/*.ts (node's own stripper, no dependencies) into dist/*.js,
// and fold the same code into ../web/bft.bundle.js, a classic script (window.BFT) that opens
// from file:// with no server. Run:  node build.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const MODULES = ["core", "steps", "sky", "stamp", "beacon", "conformance"];
const strip = (name) => stripTypeScriptTypes(readFileSync(join(here, "src", name + ".ts"), "utf8"), { mode: "strip" });

mkdirSync(join(here, "dist"), { recursive: true });
for (const m of [...MODULES, "index"]) {
  writeFileSync(join(here, "dist", m + ".js"), strip(m).replace(/(from\s+"\.\/[a-z]+)\.ts"/g, '$1.js"'));
}

// classic-script bundle: every module in its own function scope, namespaces wired by hand
let out = "// GENERATED by ts/build.mjs from ts/src/*.ts. Do not edit. Exposes window.BFT.\n(function () {\n\"use strict\";\nconst __m = {};\n";
for (const m of ["core", "steps", "sky", "stamp", "beacon"]) {
  let code = strip(m);
  code = code.replace(/^import \* as (\w+) from "\.\/(\w+)\.ts";?$/gm, "const $1 = __m.$2;");
  code = code.replace(/^import \{([^}]+)\} from "\.\/(\w+)\.ts";?$/gm, "const {$1} = __m.$2;");
  const names = [...code.matchAll(/^export (?:const|let|function|async function|class) (\w+)/gm)].map((x) => x[1]);
  code = code.replace(/^export (?=const|let|function|async function|class)/gm, "");
  out += "__m." + m + " = (function () {\n" + code + "\nreturn { " + names.join(", ") + " };\n})();\n";
}
out += "window.BFT = Object.assign({}, __m.core, __m.steps, __m.stamp, __m.beacon, { sky: __m.sky });\n})();\n";
mkdirSync(join(here, "..", "web"), { recursive: true });
writeFileSync(join(here, "..", "web", "bft.bundle.js"), out);
console.log("built dist/*.js and web/bft.bundle.js (" + out.length + " bytes)");
